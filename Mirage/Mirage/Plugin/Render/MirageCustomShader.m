// The two baked GLSL sources. Both are trivial image-shader bodies, so they
// always transpile - which is the point: they are the fallbacks every other
// path leans on when the user's own source is absent or broken.

// The default shader: the classic cosine-palette plasma, so Custom renders
// something alive out of the box (and seeds the editor). It also ships the two
// directive-driven on-screen controls the timing guide teaches on - a Center
// the pattern radiates from (a point handle) and a Scale (a ring around that
// centre) - so a fresh instance has real OSCs, not just code. Default values
// reproduce the plain plasma: Center at the frame middle, Scale 3.
//
// Doubles as the worked example for the directive syntax, so it deliberately
// shows both `group=` forms and one opt-in built-in. Keep it that way when
// touching it.
NSString *MirageCustomDefaultShaderSource(void) {
  return @"// SPDX-FileCopyrightText: 2026 overpolish\n"
         @"// SPDX-License-Identifier: MIT\n"
         @"\n"
         @"// #template generator\n"
         @"\n"
         @"// The built-in Speed lane, which scales iTime. It annotates no "
         @"uniform because\n"
         @"// it drives one the plugin already gives every shader. Opt-in, as "
         @"the seed and\n"
         @"// grain built-ins are - leave it out and the shader just runs at "
         @"speed 1. No\n"
         @"// group= here, so it lands in the default group.\n"
         @"// #speed\n"
         @"\n"
         @"// The long form of group=: name plus the SF Symbol the group "
         @"header draws.\n"
         @"// #point label=\"Center\" group={\"Pattern\", "
         @"\"circle.hexagongrid\"} osc default=\"0.5,0.5\"\n"
         @"uniform vec2 uCenter;\n"
         @"\n"
         @"// The short form: the group already has its icon from the first "
         @"control that\n"
         @"// named one, so this just joins it.\n"
         @"// #percent label=\"Scale\" group=\"Pattern\" osc=ring link=uCenter "
         @"min=25 max=400 default=100\n"
         @"uniform float uScale;\n"
         @"\n"
         @"// Cycles across the frame at 100%. Scale DIVIDES this, so the lane "
         @"reads as a\n"
         @"// zoom: turn it up and the pattern gets bigger. Multiplying would "
         @"make it a\n"
         @"// frequency instead, where raising it packs in more repetitions "
         @"and the picture\n"
         @"// appears to pull away - which is the wrong way round for "
         @"something called\n"
         @"// Scale.\n"
         @"const float kBaseFrequency = 3.0;\n"
         @"\n"
         @"void mainImage(out vec4 fragColor, in vec2 fragCoord)\n"
         @"{\n"
         @"\tvec2 uv = (fragCoord - uCenter) / iResolution.xy;\n"
         @"\tfloat freq = kBaseFrequency / max(uScale, 0.001);\n"
         @"\tvec3 col = 0.5 + 0.5 * cos(iTime + uv.xyx * freq + vec3(0.0, 2.0, "
         @"4.0));\n"
         @"\tfragColor = vec4(col, 1.0);\n"
         @"}\n";
}

// The built-in technical transform. Camera curves and gamut matrices are
// transcribed from the ASWF OpenColorIO ACES configuration v4.0 CLFs, except
// Fujifilm F-Log / F-Log2 and Nikon N-Log, which that config does not carry.
// Display curves are the published standards (sRGB, BT.1886, BT.2100 HLG,
// SMPTE ST 2084). We keep the transform in shader source (rather than a private
// render branch) so it inherits the normal browser, timeline, preview,
// persistence and stacking behaviour.
NSString *MirageColorTransformShaderSource(void) {
  return @"// SPDX-FileCopyrightText: 2026 overpolish\n"
         @"// SPDX-License-Identifier: MIT\n"
         @"\n"
         @"// Camera curves and gamut matrices: OpenColorIO Config ACES v4.0\n"
         @"// (BSD-3-Clause). Fujifilm F-Log / F-Log2 and Nikon N-Log are not "
         @"in that\n"
         @"// config; their coefficients are the vendor-published ones, "
         @"cross-checked\n"
         @"// against Colour (colour-science.org, BSD-3-Clause).\n"
         @"// #template color-transform\n"
         @"// #motionblur off\n"
         @"\n"
         @"// Both menus name a real space, because a transform cannot start "
         @"from\n"
         @"// \"unknown\". Final Cut hands this template LINEAR host values, "
         @"so an ordinary\n"
         @"// colour-managed SDR clip is already `Linear Rec.709` - the "
         @"default pair is\n"
         @"// that space in and out, an exact identity on drop. The encoded "
         @"choices (sRGB,\n"
         @"// Rec.709, Display P3, HLG, PQ, and every camera log) are for "
         @"footage whose\n"
         @"// curve the host has NOT already undone. To bypass, set Mix to 0.\n"
         @"//\n"
         @"// Every OUTPUT is a linear space. Final Cut owns the display "
         @"encode, so writing\n"
         @"// HLG or PQ code values here would encode twice; deliver HDR by "
         @"transforming to\n"
         @"// Linear Rec.2020 and letting the project's output do the rest.\n"
         @"//\n"
         @"// The HDR inputs put diffuse white at 1.0, the same place SDR "
         @"footage puts it:\n"
         @"// BT.2408 reference white, which is 203 nits for PQ and signal "
         @"0.75 for HLG.\n"
         @"// Specular highlights land above 1.0, which the float surface "
         @"holds. HLG gets\n"
         @"// its inverse OETF only - the OOTF is display rendering, and a "
         @"technical\n"
         @"// transform stays out of the look business.\n"
         @"// #choice label=\"Input\" group={\"Transform\", "
         @"\"arrow.down.right\"} dropdown options=\"Linear Rec.709,Linear "
         @"Display P3,Linear Rec.2020,sRGB,Rec.709,Display P3,Rec.2020 "
         @"HLG,Rec.2020 PQ,ACES2065-1,ACEScg,ACEScct,Apple Log / Rec.2020,ARRI "
         @"LogC3 / AWG3,ARRI LogC4 / AWG4,Blackmagic Film Gen 5,Canon C-Log2 / "
         @"Cinema Gamut,Canon C-Log3 / Cinema Gamut,DaVinci Intermediate,DJI "
         @"D-Log / D-Gamut,Fujifilm F-Log / F-Gamut,Fujifilm F-Log2 / "
         @"F-Gamut,Nikon N-Log / Rec.2020,Panasonic V-Log / V-Gamut,RED "
         @"Log3G10 / RWG,Sony S-Log2 / S-Gamut,Sony S-Log3 / S-Gamut3,Sony "
         @"S-Log3 / S-Gamut3.Cine\" default=0\n"
         @"uniform int uInput;\n"
         @"\n"
         @"// #choice label=\"Output\" group=\"Transform\" dropdown "
         @"options=\"Linear Rec.709,Linear Display P3,Linear "
         @"Rec.2020,ACEScg,ACES2065-1\" default=0\n"
         @"uniform int uOutput;\n"
         @"\n"
         @"// #percent label=\"Mix\" group=\"Transform\" default=100\n"
         @"uniform float uMix;\n"
         @"\n"
         @"vec3 rows(vec3 c, vec3 r0, vec3 r1, vec3 r2)\n"
         @"{\n"
         @"\treturn vec3(dot(r0, c), dot(r1, c), dot(r2, c));\n"
         @"}\n"
         @"\n"
         @"float srgbToLinear(float x)\n"
         @"{\n"
         @"\treturn x <= 0.04045 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4);\n"
         @"}\n"
         @"\n"
         @"float rec709ToLinear(float x)\n"
         @"{\n"
         @"\treturn x < 0.081 ? x / 4.5 : pow((x + 0.099) / 1.099, 1.0 / "
         @"0.45);\n"
         @"}\n"
         @"\n"
         @"// BT.2100 HLG, inverse OETF only, scaled so signal 0.75 (reference "
         @"white)\n"
         @"// lands on 1.0.\n"
         @"float hlgToLinear(float x)\n"
         @"{\n"
         @"\tconst float ha = 0.17883277;\n"
         @"\tconst float hb = 0.28466892;\n"
         @"\tconst float hc = 0.55991073;\n"
         @"\tfloat e = x <= 0.5 ? x * x / 3.0 : (exp((x - hc) / ha) + hb) / "
         @"12.0;\n"
         @"\treturn e * 3.7741181275;\n"
         @"}\n"
         @"\n"
         @"// SMPTE ST 2084 EOTF. Absolute nits, rescaled so BT.2408 reference "
         @"white\n"
         @"// (203 nits) lands on 1.0 and 10000 nits on 49.26.\n"
         @"float pqToLinear(float x)\n"
         @"{\n"
         @"\tfloat p = pow(max(x, 0.0), 1.0 / 78.84375);\n"
         @"\tfloat num = max(p - 0.8359375, 0.0);\n"
         @"\tfloat den = max(18.8515625 - 18.6875 * p, 1e-6);\n"
         @"\treturn pow(num / den, 1.0 / 0.1593017578125) * (10000.0 / "
         @"203.0);\n"
         @"}\n"
         @"\n"
         @"float acesCctToLinear(float x)\n"
         @"{\n"
         @"\treturn x <= 0.155251141552511\n"
         @"\t\t? (x - 0.0729055341958355) / 10.5402377416545\n"
         @"\t\t: pow(2.0, x * 17.52 - 9.72);\n"
         @"}\n"
         @"\n"
         @"float cameraLogToLinear(float y, float base, float linSlope, float "
         @"linOffset,\n"
         @"                        float logSlope, float logOffset, float "
         @"linBreak,\n"
         @"                        float toeSlope)\n"
