// The shipped transform: position, anchor, 3-axis rotation with a real
// perspective, scale, source blur and opacity. The former standalone
// MagicMove plugin, now a shader.
//
// Multi-pass, but NOT feedback - Buffer B is a pure function of the current
// source and Blur - so accumulate motion blur still works: the buffer is
// encoded once and every sub-sample reads it.
NSString *MirageMagicMoveShaderSource(void) {
  return @"// SPDX-FileCopyrightText: 2026 overpolish\n"
         @"// SPDX-License-Identifier: MIT\n"
         @"\n"
         @"// #template layout\n"
         @"\n"
         @"// Inverse transform: for each output pixel, undo the transform to "
         @"find where it\n"
         @"// came from in the source. That is why the maths reads backwards - "
         @"a scale of\n"
         @"// 200% divides.\n"
         @"// #motionblur on\n"
         @"// #alpha\n"
         @"\n"
         @"// `#point` uniforms arrive in PIXELS (bottom-origin), but "
         @"`default=` is in the\n"
         @"// lane's stored 0..1 fraction - hence 0.5 for centred.\n"
         @"// #point label=\"Position\" group={\"Transform\", \"move.3d\"} "
         @"osc=position default=\"0.5,0.5\"\n"
         @"uniform vec2 uPosition;\n"
         @"\n"
         @"// The pivot rotation and scale turn about.\n"
         @"// #point label=\"Anchor\" group=\"Transform\" osc=point square "
         @"default=\"0.5,0.5\"\n"
         @"uniform vec2 uAnchor;\n"
         @"\n"
         @"// The box OSC comes from the `osc=box` sugar like every other "
         @"Mirage control:\n"
         @"// centred on the Position handle (`link=`), aspect-locked from "
         @"`lockaspect`, and\n"
         @"// sized on the shared ring curve so it matches the rest of the "
         @"plugin.\n"
         @"// The box sits on the pivot (Position + the anchor's offset from "
         @"centre) and\n"
         @"// grows FROM it: `anchor=` pins the anchor side, so an anchor in "
         @"a corner\n"
         @"// keeps that corner put and grows the opposite one, matching how "
         @"the render\n"
         @"// scales. `link=` alone would centre the box on the pivot and "
         @"grow it evenly\n"
         @"// in all directions.\n"
         @"// #multi percent label=\"Scale\" group=\"Transform\" fields={X,Y} "
         @"lockaspect osc=box link=\"uPosition + uAnchor - vec2(0.5)\" "
         @"anchor=uAnchor min={1,1} max={800,800} default=\"100,100\"\n"
         @"uniform vec2 uScale;\n"
         @"\n"
         @"// X and Y tip the picture in perspective, Z spins it in plane. The "
         @"rings sit\n"
         @"// on the true pivot - the anchor OFFSET from centre, applied to "
         @"Position -\n"
         @"// so they stay on it when Position moves, not just when the "
         @"anchor does.\n"
         @"// #multi label=\"Rotation\" group=\"Transform\" fields={X,Y,Z} "
         @"osc={rotate x,y,z} link=\"uPosition + uAnchor - vec2(0.5)\" "
         @"default=\"0,0,0\"\n"
         @"uniform vec3 uRotation;\n"
         @"\n"
         @"// Gaussian on the SOURCE, before the transform, so a blurred clip "
         @"that then\n"
         @"// rotates keeps its blur square to itself. Percent of the frame's "
         @"short side.\n"
         @"// Applied in Buffer B; this pass only samples the result.\n"
         @"// #percent label=\"Blur\" group=\"Transform\" min=0 max=100 "
         @"default=0\n"
         @"uniform float uBlur;\n"
         @"\n"
         @"// #percent label=\"Opacity\" group=\"Transform\" min=0 max=100 "
         @"default=100\n"
         @"uniform float uOpacity;\n"
         @"\n"
         @"// Eye distance from the picture plane, in half-frames: sets how "
         @"violent the\n"
         @"// keystone is on an X/Y tip. Hard-coded in the archived plugin "
         @"too.\n"
         @"const float kEyeDistance = 2.0;\n"
         @"\n"
         @"void mainImage(out vec4 fragColor, in vec2 fragCoord)\n"
         @"{\n"
         @"\tvec2 res = iResolution.xy;\n"
         @"\tfloat aspect = res.x / res.y;\n"
         @"\n"
         @"\tvec2 p = fragCoord / res - uPosition / res;\n"
         @"\tvec2 anchor = uAnchor / res - 0.5;\n"
         @"\tp -= anchor;\n"
         @"\tp.x *= aspect;\n"
         @"\n"
         @"\t// Already radians and already negated - the wrapper emits\n"
         @"\t// `radians(-lane)`. Y is flipped because the archived shader "
         @"mirrored Y\n"
         @"\t// into the ray and back, which cancels for Ry but inverts Rx and "
         @"Rz.\n"
         @"\tvec3 rad = uRotation * vec3(1.0, -1.0, 1.0);\n"
         @"\tfloat cx = cos(rad.x), sx = sin(rad.x);\n"
         @"\tfloat cy = cos(rad.y), sy = sin(rad.y);\n"
         @"\tfloat cz = cos(rad.z), sz = sin(rad.z);\n"
         @"\tvec3 col0 = vec3(cy * cz + sy * sx * sz, cx * sz, -sy * cz + cy * "
         @"sx * sz);\n"
         @"\tvec3 col1 = vec3(-cy * sz + sy * sx * cz, cx * cz, sy * sz + cy * "
         @"sx * cz);\n"
         @"\tvec3 col2 = vec3(sy * cx, -sx, cy * cx);\n"
         @"\n"
         @"\t// Ray from the eye through this pixel, rotated into the "
         @"picture's frame:\n"
         @"\t// where it crosses the picture plane is the source pixel. Doing "
         @"it as a ray\n"
         @"\t// is what makes an X/Y tip a real perspective instead of a "
         @"squash.\n"
         @"\tvec3 Ow = vec3(0.0, 0.0, -kEyeDistance);\n"
         @"\tvec3 Dw = vec3(p.x, p.y, kEyeDistance);\n"
         @"\tvec3 O = vec3(dot(col0, Ow), dot(col1, Ow), dot(col2, Ow));\n"
         @"\tvec3 D = vec3(dot(col0, Dw), dot(col1, Dw), dot(col2, Dw));\n"
         @"\n"
         @"\tif (abs(D.z) < 0.0001)\n"
         @"\t{\n"
         @"\t\tfragColor = vec4(0.0);\n"
         @"\t\treturn;\n"
         @"\t}\n"
         @"\n"
         @"\tfloat tHit = -O.z / D.z;\n"
         @"\n"
         @"\t// Behind the eye: the far half of a picture tipped past 90 "
         @"degrees, which\n"
         @"\t// would otherwise fold back through itself and mirror.\n"
         @"\tif (tHit <= 0.0)\n"
         @"\t{\n"
         @"\t\tfragColor = vec4(0.0);\n"
         @"\t\treturn;\n"
         @"\t}\n"
         @"\n"
         @"\tp = vec2(O.x + tHit * D.x, O.y + tHit * D.y);\n"
         @"\tp.x /= aspect;\n"
         @"\n"
         @"\tif (abs(uScale.x) < 0.001 || abs(uScale.y) < 0.001)\n"
         @"\t{\n"
         @"\t\tfragColor = vec4(0.0);\n"
         @"\t\treturn;\n"
         @"\t}\n"
         @"\n"
         @"\tp /= uScale;\n"
         @"\tvec2 src = p + anchor + 0.5;\n"
         @"\n"
         @"\t// fwidth is in output pixels after the inverse map, so the "
         @"feather widens\n"
         @"\t// automatically as the picture is scaled down.\n"
         @"\tvec2 fw = fwidth(src);\n"
         @"\tfloat edgeAA = smoothstep(0.0, fw.x, src.x)\n"
         @"\t               * smoothstep(0.0, fw.x, 1.0 - src.x)\n"
         @"\t               * smoothstep(0.0, fw.y, src.y)\n"
         @"\t               * smoothstep(0.0, fw.y, 1.0 - src.y);\n"
         @"\n"
         @"\tif (edgeAA <= 0.0)\n"
         @"\t{\n"
         @"\t\tfragColor = vec4(0.0);\n"
         @"\t\treturn;\n"
         @"\t}\n"
         @"\n"
         @"\t// Buffer B holds the blurred source, built once for the whole "
         @"frame. Under\n"
         @"\t// motion blur this pass re-runs per sub-sample and each one is a "
         @"single\n"
         @"\t// fetch, instead of every sample re-blurring the same source.\n"
         @"\tvec4 c = texture(iChannel1, src);\n"
         @"\n"
         @"\t// `#alpha` makes the wrapper premultiply on output, so this must "
         @"return\n"
         @"\t// STRAIGHT colour - the source arrives premultiplied, hence the "
         @"divide.\n"
         @"\t// The blur above deliberately accumulates premultiplied, which "
         @"is the\n"
         @"\t// correct space to filter in.\n"
         @"\tfloat outA = c.a * uOpacity * edgeAA;\n"
         @"\tfragColor = (c.a > 0.0001) ? vec4(c.rgb / c.a, outA) : "
         @"vec4(0.0);\n"
         @"}\n";
}

// MagicMove's Buffer B: the source blur, computed once per frame so the
// Image pass costs ONE fetch per motion-blur sub-sample instead of
// re-blurring the same source N times.
//
// Buffer A is skipped: channel routing is positional, so a present Buffer A
// would seize iChannel0 and this pass would lose the source clip.
NSString *MirageMagicMoveBufferBSource(void) {
  return @"// Pool-alignment prefix: a VERBATIM copy of the Image section's "
         @"directives, in\n"
         @"// the same order, up to the one this pass uses. Offsets are "
         @"assigned\n"
         @"// colours-first then scalars in source order, so an identical "
         @"prefix lands on\n"
         @"// identical slots. Nothing here may be reordered or omitted.\n"
         @"// #point label=\"Position\" osc=position default=\"0.5,0.5\"\n"
         @"uniform vec2 uPosition;\n"
         @"\n"
         @"// #point label=\"Anchor\" osc=point square default=\"0.5,0.5\"\n"
         @"uniform vec2 uAnchor;\n"
         @"\n"
         @"// #multi percent label=\"Scale\" fields={X,Y} lockaspect min={1,1} "
         @"max={800,800} default=\"100,100\"\n"
         @"uniform vec2 uScale;\n"
         @"\n"
         @"// #multi label=\"Rotation\" fields={X,Y,Z} osc={rotate x,y,z} "
         @"default=\"0,0,0\"\n"
         @"uniform vec3 uRotation;\n"
         @"\n"
         @"// #percent label=\"Blur\" min=0 max=100 default=0\n"
         @"uniform float uBlur;\n"
         @"\n"
         @"// The source blur, computed ONCE per frame. The Image pass then "
         @"samples this\n"
         @"// with one fetch per motion-blur sub-sample instead of re-blurring "
         @"the same\n"
         @"// source N times - which is the whole reason the blur lives in a "
         @"buffer.\n"
         @"// Non-feedback (it reads iChannel0 only), so accumulate motion "
         @"blur shares it.\n"
         @"const int kTaps = 32;\n"
         @"const float kGoldenAngle = 2.39996323;\n"
         @"\n"
         @"float mmHash(vec2 p)\n"
         @"{\n"
         @"\tvec3 p3 = fract(vec3(p.xyx) * 0.1031);\n"
         @"\tp3 += dot(p3, p3.yzx + 33.33);\n"
         @"\treturn fract((p3.x + p3.y) * p3.z);\n"
         @"}\n"
         @"\n"
         @"void mainImage(out vec4 O, in vec2 fc)\n"
         @"{\n"
         @"\tvec2 res = iResolution.xy;\n"
         @"\tvec2 uv = fc / res;\n"
         @"\tfloat sigmaPx = uBlur * min(res.x, res.y) * 0.1;\n"
         @"\n"
         @"\tif (sigmaPx < 0.25)\n"
         @"\t{\n"
         @"\t\tO = texture(iChannel0, uv);\n"
         @"\t\treturn;\n"
         @"\t}\n"
         @"\n"
         @"\tvec2 sigmaUV = vec2(sigmaPx) / res;\n"
         @"\tfloat a0 = mmHash(fc) * 6.2831853;\n"
         @"\tvec4 acc = vec4(0.0);\n"
         @"\tfloat wacc = 0.0;\n"
         @"\n"
         @"\tfor (int i = 0; i < kTaps; i++)\n"
         @"\t{\n"
         @"\t\tfloat fi = float(i) + 0.5;\n"
         @"\t\tfloat r = sqrt(fi / float(kTaps));\n"
         @"\t\tfloat a = a0 + fi * kGoldenAngle;\n"
         @"\t\tfloat w = exp(-2.0 * r * r);\n"
         @"\t\tacc += texture(iChannel0, uv + vec2(cos(a), sin(a)) * r * "
         @"sigmaUV * 2.0) * w;\n"
         @"\t\twacc += w;\n"
         @"\t}\n"
         @"\n"
         @"\tO = acc / wacc;\n"
         @"}\n";
}

// Shared by every Frame pass: the rounded-window SDF, a hash, and one half of
// a separable gaussian.
NSString *MirageFrameCommonSource(void) {
  return @"// Signed distance in pixels to the rounded edge, negative inside. "
         @"The p-norm\n"
         @"// handles the corner falloff outside; min(max(d.x, d.y), 0.0) "
         @"supplies real\n"
         @"// depth inside. Clamping that to zero saturates the interior at "
         @"-r, which makes\n"
         @"// any border wider than the corner radius read as \"near the "
         @"edge\" everywhere\n"
         @"// and flood the shape.\n"
         @"float roundedSDF(vec2 p, vec2 halfSize, float r, float radius01)\n"
         @"{\n"
         @"\tfloat power = mix(5.0, 2.0, radius01);\n"
         @"\tvec2 d = abs(p) - halfSize + r;\n"
         @"\tvec2 o = max(d, 0.0);\n"
         @"\tfloat outside = pow(pow(o.x, power) + pow(o.y, power), 1.0 / "
         @"power) - r;\n"
         @"\tfloat inside = min(max(d.x, d.y), 0.0);\n"
         @"\treturn outside + inside;\n"
         @"}\n"
         @"\n"
         @"// Cheap 2D hash: the glow's grain, and the blur's per-pixel "
         @"jitter.\n"
         @"float frameHash(vec2 p)\n"
         @"{\n"
         @"\tvec3 p3 = fract(vec3(p.xyx) * 0.1031);\n"
         @"\tp3 += dot(p3, p3.yzx + 33.33);\n"
         @"\treturn fract((p3.x + p3.y) * p3.z);\n"
         @"}\n"
         @"\n"
         @"// One half of a separable gaussian, radius in pixels. 33 taps have "
         @"to cover\n"
         @"// whatever Glow Size asks for, so at a wide radius the spacing is "
         @"far past a\n"
         @"// texel and the kernel undersamples itself - that's the banding. "
         @"`jit` offsets\n"
         @"// every pixel's tap positions by up to half a step, which turns "
         @"that banding\n"
         @"// into fine grain instead. At glow softness the grain is "
         @"invisible; the bands\n"
         @"// were not.\n"
         @"vec4 frameBlurTex(sampler2D tex, vec2 uv, vec2 dir, vec2 res, float "
         @"radiusPx,\n"
         @"                  float jit)\n"
         @"{\n"
         @"\tvec2 step = dir * (max(radiusPx, 1.0) / 16.0) / res;\n"
         @"\tvec4 acc = vec4(0.0);\n"
         @"\tfloat wacc = 0.0;\n"
         @"\tfor (int i = -16; i <= 16; i++)\n"
         @"\t{\n"
         @"\t\tfloat fi = float(i) + jit;\n"
         @"\t\tfloat x = fi / 16.0;\n"
         @"\t\tfloat w = exp(-4.5 * x * x);\n"
         @"\t\tacc += texture(tex, uv + step * fi) * w;\n"
         @"\t\twacc += w;\n"
         @"\t}\n"
         @"\treturn acc / wacc;\n"
         @"}\n";
}

