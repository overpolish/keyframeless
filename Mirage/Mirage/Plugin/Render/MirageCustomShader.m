         @"\tfloat q = linSlope * linBreak + linOffset;\n"
         @"\tfloat yBreak = logSlope * log(q) / log(base) + logOffset;\n"
         @"\tfloat slope = toeSlope > 0.0\n"
         @"\t\t? toeSlope\n"
         @"\t\t: logSlope * linSlope / (log(base) * q);\n"
         @"\treturn y >= yBreak\n"
         @"\t\t? (pow(base, (y - logOffset) / logSlope) - linOffset) / "
         @"linSlope\n"
