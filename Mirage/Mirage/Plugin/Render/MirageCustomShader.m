         @"logSlope, logOffset, linBreak, toeSlope),\n"
         @"\t            cameraLogToLinear(c.b, base, linSlope, linOffset, "
         @"logSlope, logOffset, linBreak, toeSlope));\n"
         @"}\n"
         @"\n"
         @"float appleLogToLinear(float y)\n"
         @"{\n"
         @"\tconst float cut = 0.2085553160;\n"
         @"\treturn y < cut ? sqrt(max(y, 0.0) / 47.28711236) - 0.05641088\n"
         @"\t               : pow(2.0, (y - 0.69336945) / 0.08550479) - "
         @"0.00964052;\n"
         @"}\n"
         @"\n"
         @"float canonLog2ToLinear(float y)\n"
         @"{\n"
         @"\tfloat v = y < 0.092864125\n"
         @"\t\t? -(pow(10.0, (0.092864125 - y) / 0.24136077) - 1.0)\n"
         @"\t\t:  (pow(10.0, (y - 0.092864125) / 0.24136077) - 1.0);\n"
         @"\treturn 0.9 * v / 87.099375;\n"
         @"}\n"
         @"\n"
         @"float canonLog3ToLinear(float y)\n"
         @"{\n"
         @"\tif (y < 0.09746547)\n"
         @"\t\treturn -0.9 * (pow(10.0, (0.12783901 - y) / 0.36726845) - 1.0) "
         @"/ 14.98325;\n"
         @"\tif (y <= 0.15277891)\n"
         @"\t\treturn 0.9 * (y - 0.12512219) / 1.9754798;\n"
         @"\treturn 0.9 * (pow(10.0, (y - 0.12240537) / 0.36726845) - 1.0) / "
         @"14.98325;\n"
         @"}\n"
         @"\n"
         @"// F-Log and F-Log2 share one curve shape and differ only in "
         @"coefficients.\n"
         @"float fLogToLinear(float y, float cut2, float fa, float fb, float "
         @"fc, float fd,\n"
         @"                   float fe, float ff)\n"
         @"{\n"
         @"\treturn y < cut2 ? (y - ff) / fe\n"
         @"\t                : pow(10.0, (y - fd) / fc) / fa - fb / fa;\n"
         @"}\n"
         @"\n"
         @"float nLogToLinear(float y)\n"
         @"{\n"
         @"\treturn y < 0.4418377321603128\n"
         @"\t\t? pow(max(y, 0.0) / 0.635386119257087, 3.0) - 0.0075\n"
