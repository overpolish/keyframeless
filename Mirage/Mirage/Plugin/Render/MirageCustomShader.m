#import "MirageCustomShader.h"

#import "Constants.h" // declares MirageCustomDefaultShaderSource

// The two baked GLSL sources. Both are trivial image-shader bodies, so they
// always transpile - which is the point: they are the fallbacks every other
// path leans on when the user's own source is absent or broken.

// The default shader: the classic cosine-palette plasma, so Custom renders
// something alive out of the box (and seeds the editor). It also ships the two
// directive-driven on-screen controls the timing guide teaches on - a Center
// the pattern radiates from (a point handle) and a Scale (a ring around that
// centre) - so a fresh instance has real OSCs, not just code. Default values
// reproduce the plain plasma: Center at the frame middle, Scale 3.
NSString *MirageCustomDefaultShaderSource(void) {
  return @"// #point label=\"Center\" osc default=\"0.5,0.5\"\n"
         @"uniform vec2 uCenter;\n"
         @"// #float label=\"Scale\" osc=ring link=uCenter min=1 max=8 "
         @"default=3\n"
         @"uniform float uScale;\n"
         @"\n"
         @"void mainImage( out vec4 fragColor, in vec2 fragCoord ) {\n"
         @"    vec2 uv = (fragCoord - uCenter) / iResolution.xy;\n"
         @"    vec3 col = 0.5 + 0.5 * cos(iTime + uv.xyx * uScale + "
         @"vec3(0.0, 2.0, 4.0));\n"
         @"    fragColor = vec4(col, 1.0);\n"
         @"}\n";
}

// Shared by every Frame pass: the rounded-window SDF, a hash, and one half of
// a separable gaussian.
NSString *MirageFrameCommonSource(void) {
  return @"// Signed distance in pixels to the rounded edge, negative inside. "
         @"The p-norm\n"
         @"// handles the corner falloff outside; min(max(d.x, d.y), 0.0) "
         @"supplies real\n"
         @"// depth inside. Clamping that to zero saturates the interior at "
         @"-r, which makes\n"
         @"// any border wider than the corner radius read as \"near the "
         @"edge\" everywhere\n"
         @"// and flood the shape.\n"
         @"float roundedSDF(vec2 p, vec2 halfSize, float r, float radius01)\n"
         @"{\n"
         @"\tfloat power = mix(5.0, 2.0, radius01);\n"
         @"\tvec2 d = abs(p) - halfSize + r;\n"
         @"\tvec2 o = max(d, 0.0);\n"
         @"\tfloat outside = pow(pow(o.x, power) + pow(o.y, power), 1.0 / "
         @"power) - r;\n"
         @"\tfloat inside = min(max(d.x, d.y), 0.0);\n"
         @"\treturn outside + inside;\n"
         @"}\n"
         @"\n"
         @"// Cheap 2D hash: the glow's grain, and the blur's per-pixel "
         @"jitter.\n"
         @"float frameHash(vec2 p)\n"
         @"{\n"
         @"\tvec3 p3 = fract(vec3(p.xyx) * 0.1031);\n"
         @"\tp3 += dot(p3, p3.yzx + 33.33);\n"
         @"\treturn fract((p3.x + p3.y) * p3.z);\n"
         @"}\n"
         @"\n"
         @"// One half of a separable gaussian, radius in pixels. 33 taps have "
         @"to cover\n"
         @"// whatever Glow Size asks for, so at a wide radius the spacing is "
         @"far past a\n"
         @"// texel and the kernel undersamples itself - that's the banding. "
         @"`jit` offsets\n"
         @"// every pixel's tap positions by up to half a step, which turns "
         @"that banding\n"
         @"// into fine grain instead. At glow softness the grain is "
         @"invisible; the bands\n"
         @"// were not.\n"
         @"vec4 frameBlurTex(sampler2D tex, vec2 uv, vec2 dir, vec2 res, float "
         @"radiusPx,\n"
         @"                  float jit)\n"
         @"{\n"
         @"\tvec2 step = dir * (max(radiusPx, 1.0) / 16.0) / res;\n"
         @"\tvec4 acc = vec4(0.0);\n"
         @"\tfloat wacc = 0.0;\n"
         @"\tfor (int i = -16; i <= 16; i++)\n"
         @"\t{\n"
         @"\t\tfloat fi = float(i) + jit;\n"
         @"\t\tfloat x = fi / 16.0;\n"
         @"\t\tfloat w = exp(-4.5 * x * x);\n"
         @"\t\tacc += texture(tex, uv + step * fi) * w;\n"
         @"\t\twacc += w;\n"
         @"\t}\n"
         @"\treturn acc / wacc;\n"
         @"}\n";
}

// Frame's Buffer B: the PREP pass - the picture premultiplied by its own
// silhouette, exactly what the old Glow plugin fed to MPS. Blurring this and
// dividing the colour back out at the end is what makes the glow vary smoothly
// in every direction.
//
// Buffer A is skipped throughout: channel routing is positional, so a present
// Buffer A would seize iChannel0 and every pass would lose the source clip.
NSString *MirageFrameBufferBSource(void) {
  return @"// Pool-alignment prefix: a VERBATIM copy of the Image section's "
         @"first\n"
         @"// directives, in the same order. Offsets are assigned "
         @"colours-first then\n"
         @"// scalars in source order, so an identical prefix lands on "
         @"identical slots -\n"
         @"// that's the whole reason these are here, and why nothing may be "
         @"reordered or\n"
         @"// omitted. No `group=`: lanes come from the Image section alone.\n"
         @"// #color label=\"Border Color\" default=\"#FFFFFF\"\n"
         @"uniform vec4 uBorderColor;\n"
         @"\n"
         @"// #color label=\"Glow Color\" default=\"#FFFFFFB3\"\n"
         @"uniform vec4 uGlowColor;\n"
         @"\n"
         @"// #percent label=\"Radius\" min=0 max=100 default=20\n"
         @"uniform float uRadius;\n"
         @"\n"
         @"// #multi label=\"Crop\" fields={W,H,X,Y} units={px,px,px,px} "
         @"min={0,0,,} max={1,1,,} default=\"1,1,0,0\"\n"
         @"uniform vec4 uCrop;\n"
         @"\n"
         @"// #percent label=\"Size\" min=1 max=400 default=100\n"
         @"uniform float uSize;\n"
         @"\n"
         @"// #point label=\"Position\" default=\"0,0\"\n"
         @"uniform vec2 uPosition;\n"
         @"\n"
         @"// #float label=\"Border Width\" units=\"px\" min=0 max=200 "
         @"default=0\n"
         @"uniform float uBorderWidth;\n"
         @"\n"
         @"// #float label=\"Glow Size\" units=\"px\" min=0 max=300 default=0\n"
         @"uniform float uGlowSize;\n"
         @"\n"
         @"void mainImage(out vec4 O, in vec2 fc)\n"
         @"{\n"
         @"\tvec2 res = iResolution.xy;\n"
         @"\tfloat sz = max(uSize, 0.001);\n"
         @"\tvec2 halfSize = uCrop.xy * res * 0.5 * sz;\n"
         @"\tvec2 winCentre = vec2(uCrop.z + uCrop.x * 0.5,\n"
         @"\t                      1.0 - uCrop.w - uCrop.y * 0.5) * res;\n"
         @"\tvec2 p = fc - (winCentre + uPosition);\n"
         @"\tfloat r = uRadius * min(halfSize.x, halfSize.y);\n"
         @"\t// Grown by the border, so a bordered frame casts the glow of its "
         @"border\n"
         @"\t// rather than of the content inside it.\n"
         @"\tfloat d = roundedSDF(p, halfSize, r, uRadius) - uBorderWidth;\n"
         @"\tfloat ins = 1.0 - smoothstep(0.0, max(fwidth(d), 1e-4) * 2.0, "
         @"d);\n"
         @"\tvec2 srcUV = (winCentre + p / sz) / res;\n"
         @"\tvec3 c = texture(iChannel0, clamp(srcUV, vec2(0.0), "
         @"vec2(1.0))).rgb;\n"
         @"\tO = vec4(c * ins, ins); // premultiplied\n"
         @"}\n";
}

